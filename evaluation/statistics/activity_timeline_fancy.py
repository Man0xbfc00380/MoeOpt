#!/usr/bin/env python
# -*- coding: utf-8 -*-

"""
Fancy academic-style visualization for Activity Timeline and Execution Time Breakdown.

Figure layout:
- Top subplot: 4-chip activity timeline using BrokenBarHCollection (receive, ddr_load, compute, send)
- Bottom subplot: execution time breakdown per chip, stacked by dominant activity

Data source: results/trace_per_chip.csv generated by runner_one_layer.py.
If missing, this script will invoke a single run with:
    python runner_one_layer.py --model Phi3.5-MoE --dataset C4 --config configs/FSE-DP_16_2_mul_2.json --write_csv

Output: anim/evaluation/statistics/activity_timeline_fancy.png
"""

import sys
import subprocess
from pathlib import Path
from typing import Dict, Tuple, List
import csv
import numpy as np
import matplotlib.pyplot as plt


MODEL = 'Phi3.5-MoE'
DATASET = 'c4'
CFG_REL = 'configs/FSE-DP_16_2_mul_2.json'

# Plot range configuration (None means use full range)
# Set START_FRAME/END_FRAME to integers to slice timeline [START_FRAME, END_FRAME)
START_FRAME = None
END_FRAME = None

# Global font configuration
plt.rcParams.update({
    'font.family': 'sans-serif',
    'font.sans-serif': ['Arial'],
})


def _run_once(evaluation_dir: Path) -> Path:
    runner_path = evaluation_dir / 'runner_one_layer.py'
    cfg_path = evaluation_dir / CFG_REL
    out_dir = evaluation_dir / 'results'
    cmd = [
        sys.executable,
        str(runner_path),
        '--model', MODEL,
        '--dataset', DATASET,
        '--config', str(cfg_path),
        '--write_csv',
    ]
    subprocess.run(cmd, cwd=str(evaluation_dir), capture_output=True, text=False, check=False)
    return out_dir / 'trace_per_chip.csv'


def _read_per_chip_csv(per_chip_csv: Path) -> List[Dict]:
    rows: List[Dict] = []
    with per_chip_csv.open('r', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for r in reader:
            rows.append(r)
    return rows


def _segments_from_flags(flags: np.ndarray) -> List[Tuple[int, int]]:
    # flags: shape (T,), values 0/1; return list of (start, end) with end exclusive
    segs: List[Tuple[int, int]] = []
    in_seg = False
    start = 0
    T = len(flags)
    for i in range(T):
        if flags[i] and not in_seg:
            in_seg = True
            start = i
        elif (not flags[i]) and in_seg:
            in_seg = False
            segs.append((start, i))
    if in_seg:
        segs.append((start, T))
    return segs


def _build_timeline(rows: List[Dict]) -> Tuple[np.ndarray, int]:
    frames = sorted({int(r['frame']) for r in rows})
    T = (frames[-1] + 1) if frames else 0
    chips = sorted({int(r['chip_index']) for r in rows})
    C = max(chips) + 1 if chips else 0
    C = max(C, 4)

    # activity indices: 0=receive, 1=ddr_load, 2=compute, 3=send
    timeline = np.zeros((C, T, 4), dtype=np.int32)
    for r in rows:
        ci = int(r.get('chip_index', 0))
        fi = int(r.get('frame', 0))
        recv = int(r.get('receive', 0) or 0)
        ddr = int(r.get('ddr_load', 0) or 0)
        cmp_flag = int(r.get('compute_active', 0) or 0)
        send = int(r.get('send', 0) or 0)
        if 'compute_active' not in r:
            try:
                cmp_flag = 1 if float(r.get('compute_util', 0.0) or 0.0) > 0.0 else 0
            except Exception:
                cmp_flag = 0
        if ci < C and fi < T:
            timeline[ci, fi, 0] = recv
            timeline[ci, fi, 1] = ddr
            timeline[ci, fi, 2] = cmp_flag
            timeline[ci, fi, 3] = send
    return timeline[:4], T


def _compute_dominant_breakdown(timeline: np.ndarray) -> np.ndarray:
    """Compute dominant-activity breakdown per chip.
    Priority: compute > send > receive > ddr_load > idle
    Returns shape (4, 5): percentages for [compute, send, receive, ddr_load, idle]
    """
    C, T, _ = timeline.shape
    breakdown = np.zeros((C, 5), dtype=np.float64)
    for c in range(C):
        comp = timeline[c, :, 2]
        send = timeline[c, :, 3]
        recv = timeline[c, :, 0]
        ddr = timeline[c, :, 1]
        dominant = np.zeros(T, dtype=np.int32)
        for t in range(T):
            if comp[t]:
                dominant[t] = 0  # compute
            elif send[t]:
                dominant[t] = 1  # send
            elif recv[t]:
                dominant[t] = 2  # receive
            elif ddr[t]:
                dominant[t] = 3  # ddr_load
            else:
                dominant[t] = 4  # idle
        for k in range(5):
            breakdown[c, k] = np.sum(dominant == k) / max(1, T)
    return breakdown


def plot_fancy(timeline: np.ndarray, T: int, breakdown: np.ndarray, out_path: Path) -> None:
    # Style
    plt.rcParams.update({
        'font.size': 10,
        'axes.labelsize': 10,
        'axes.titlesize': 11,
        'legend.fontsize': 9,
        'lines.linewidth': 1.6,
    })

    colors = {
        'receive': '#1f77b4',      # blue
        'ddr_load': '#ff7f0e',     # orange
        'compute': '#2ca02c',      # green
        'send': '#d62728',         # red
        'idle': '#9c9c9c',         # grey
    }
    hatches = {
        'receive': '',
        'ddr_load': '///',
        'compute': '',
        'send': '\\\\',
    }

    fig = plt.figure(figsize=(8.0, 6.2), dpi=240)
    gs = fig.add_gridspec(2, 1, height_ratios=[2.2, 1.2], hspace=0.25)

    # Top: timeline
    ax_top = fig.add_subplot(gs[0])
    band_height = 0.8
    inner_thick = 0.12
    offsets = {
        'receive': -0.27,
        'ddr_load': -0.09,
        'compute': 0.09,
        'send': 0.27,
    }
    activities = ['receive', 'ddr_load', 'compute', 'send']

    # Alternate background bands per chip
    for chip in range(4):
        y0 = chip - band_height/2
        ax_top.add_patch(plt.Rectangle((0, y0), max(1, T), band_height,
                                       facecolor='#f5f5f5' if chip % 2 == 0 else '#ffffff',
                                       edgecolor='none', alpha=1.0))

    # Broken bars per activity
    for chip in range(4):
        for idx, act in enumerate(activities):
            flags = timeline[chip, :, idx if act != 'compute' else 2]
            segs = _segments_from_flags(flags)
            if not segs:
                continue
            xranges = [(s, e - s) for s, e in segs]
            ycenter = chip + offsets[act]
            ax_top.broken_barh(xranges, (ycenter - inner_thick/2, inner_thick),
                               facecolors=colors[act], edgecolors=colors[act], alpha=0.95)

    ax_top.set_ylim(-0.6, 3.6)
    ax_top.set_xlim(0, max(1, T))
    ax_top.set_yticks([0, 1, 2, 3])
    ax_top.set_yticklabels([f"Chip-{i}" for i in range(4)])
    ax_top.set_xlabel('Frame')
    ax_top.set_title('Activity Timeline (Phi3.5-MoE × C4, EP)')
    ax_top.grid(axis='x', linestyle='--', alpha=0.25)
    for spine in ['top', 'right']:
        ax_top.spines[spine].set_visible(False)

    # Legend
    handles = [plt.Line2D([0], [0], color=colors[k], lw=3, label=k) for k in activities]
    ax_top.legend(handles=handles, loc='upper right', ncol=2)

    # Bottom: execution time breakdown (dominant activity) per chip
    ax_bot = fig.add_subplot(gs[1])
    x = np.arange(4)
    width = 0.65
    comp = breakdown[:, 0]
    send = breakdown[:, 1]
    recv = breakdown[:, 2]
    ddr = breakdown[:, 3]
    idle = breakdown[:, 4]

    bottom = np.zeros_like(comp)
    p1 = ax_bot.bar(x, comp, width, label='compute', color=colors['compute'])
    bottom += comp
    p2 = ax_bot.bar(x, send, width, bottom=bottom, label='send', color=colors['send'], hatch=hatches['send'], edgecolor='black', linewidth=0.3)
    bottom += send
    p3 = ax_bot.bar(x, recv, width, bottom=bottom, label='receive', color=colors['receive'])
    bottom += recv
    p4 = ax_bot.bar(x, ddr, width, bottom=bottom, label='ddr_load', color=colors['ddr_load'], hatch=hatches['ddr_load'], edgecolor='black', linewidth=0.3)
    bottom += ddr
    p5 = ax_bot.bar(x, idle, width, bottom=bottom, label='idle', color=colors['idle'])

    ax_bot.set_xticks(x)
    ax_bot.set_xticklabels([f"Chip-{i}" for i in range(4)])
    ax_bot.set_ylim(0, 1.0)
    ax_bot.set_ylabel('Fraction of Frames')
    ax_bot.set_title('Execution Time Breakdown (Dominant Activity)')
    ax_bot.grid(axis='y', linestyle='--', alpha=0.25)
    for spine in ['top', 'right']:
        ax_bot.spines[spine].set_visible(False)
    ax_bot.legend(loc='upper right', ncol=2)

    # Footnote
    fig.text(0.01, 0.01, 'Breakdown uses dominant activity per frame: compute > send > receive > ddr_load > idle', fontsize=8, color='#666666')

    out_path.parent.mkdir(parents=True, exist_ok=True)
    # 使用 constrained_layout 替代 tight_layout 以避免警告
    fig.set_constrained_layout_pads(w_pad=0.04, h_pad=0.04)
    fig.savefig(out_path)
    plt.close(fig)


def main():
    statistics_dir = Path(__file__).resolve().parent
    evaluation_dir = statistics_dir.parent
    per_chip_csv = evaluation_dir / 'results' / 'trace_per_chip.csv'
    if not per_chip_csv.exists():
        per_chip_csv = _run_once(evaluation_dir)
    rows = _read_per_chip_csv(per_chip_csv)
    timeline, T = _build_timeline(rows)
    # Apply optional frame slicing
    s = 0 if START_FRAME is None else max(0, int(START_FRAME))
    e = T if END_FRAME is None else min(T, int(END_FRAME))
    if e <= s:
        e = min(T, s + 1)
    timeline = timeline[:, s:e, :]
    T = e - s
    breakdown = _compute_dominant_breakdown(timeline)
    out_path = statistics_dir / 'results' / 'activity_timeline_fancy.png'
    plot_fancy(timeline, T, breakdown, out_path)
    print(f"Saved fancy timeline to: {out_path}")


if __name__ == '__main__':
    main()